-- ---------------------------------------------------------------------
-- USERS  (User <|-- Customer, Admin)  -> single table + role discriminator
-- ---------------------------------------------------------------------
CREATE TABLE users (
    user_id               VARCHAR(36)  PRIMARY KEY,
    role                  VARCHAR(10)  NOT NULL,
    name                  VARCHAR(100) NOT NULL,
    national_id           VARCHAR(20)  NOT NULL UNIQUE,
    phone                 VARCHAR(20),
    email                 VARCHAR(150) UNIQUE,
    username              VARCHAR(50)  NOT NULL UNIQUE,
    password_hash         VARCHAR(255) NOT NULL,
    status                VARCHAR(10)  NOT NULL DEFAULT 'ACTIVE',
    failed_login_attempts INT          NOT NULL DEFAULT 0,
    created_at            TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at         TIMESTAMP,
    last_logout_at        TIMESTAMP,
    CONSTRAINT ck_users_role   CHECK (role IN ('CUSTOMER', 'ADMIN')),
    CONSTRAINT ck_users_status CHECK (status IN ('ACTIVE', 'LOCKED', 'SUSPENDED')),
    CONSTRAINT ck_users_failed CHECK (failed_login_attempts >= 0)
);

-- ---------------------------------------------------------------------
-- ACCOUNTS  (Customer 1 --owns--> 0..* Account)
-- ---------------------------------------------------------------------
CREATE TABLE accounts (
    account_number  VARCHAR(20)    PRIMARY KEY,
    customer_id     VARCHAR(36)    NOT NULL,
    balance         DECIMAL(19, 2) NOT NULL DEFAULT 0,
    status          VARCHAR(10)    NOT NULL DEFAULT 'ACTIVE',
    type            VARCHAR(10)    NOT NULL,
    opened_at       TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    daily_limit     DECIMAL(19, 2) NOT NULL DEFAULT 0,
    withdrawn_today DECIMAL(19, 2) NOT NULL DEFAULT 0,
    last_reset_date DATE           NOT NULL DEFAULT CURRENT_DATE,
    CONSTRAINT fk_accounts_customer FOREIGN KEY (customer_id) REFERENCES users (user_id),
    CONSTRAINT ck_accounts_status   CHECK (status IN ('ACTIVE', 'FROZEN', 'CLOSED')),
    CONSTRAINT ck_accounts_type     CHECK (type IN ('SAVINGS', 'CHECKING')),
    CONSTRAINT ck_accounts_balance  CHECK (balance >= 0),
    CONSTRAINT ck_accounts_limit    CHECK (daily_limit >= 0 AND withdrawn_today >= 0)
);

-- ---------------------------------------------------------------------
-- CARDS  (Account 1 <>-- issued --> 0..* Card)  composition
-- ---------------------------------------------------------------------
CREATE TABLE cards (
    card_number          VARCHAR(19) PRIMARY KEY,
    account_number       VARCHAR(20) NOT NULL,
    pin_hash             VARCHAR(255) NOT NULL,
    expiry_date          DATE        NOT NULL,
    status               VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    failed_pin_attempts  INT         NOT NULL DEFAULT 0,
    issued_at            TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_cards_account FOREIGN KEY (account_number)
        REFERENCES accounts (account_number) ON DELETE CASCADE,
    CONSTRAINT ck_cards_status  CHECK (status IN ('ACTIVE', 'FROZEN', 'BLOCKED', 'EXPIRED')),
    CONSTRAINT ck_cards_failed  CHECK (failed_pin_attempts >= 0)
);

-- ---------------------------------------------------------------------
-- ATMS
-- ---------------------------------------------------------------------
CREATE TABLE atms (
    atm_id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    location                    VARCHAR(255)   NOT NULL,
    status                      VARCHAR(15)    NOT NULL DEFAULT 'OFFLINE',
    max_withdraw_per_transaction DECIMAL(19, 2) NOT NULL DEFAULT 5000,
    max_deposit_per_transaction  DECIMAL(19, 2) NOT NULL DEFAULT 20000,
    note_multiple               INT            NOT NULL DEFAULT 50,
    last_heartbeat_at           TIMESTAMP,
    CONSTRAINT ck_atms_status CHECK (status IN ('IN_SERVICE', 'OUT_OF_SERVICE', 'MAINTENANCE', 'OFFLINE')),
    CONSTRAINT ck_atms_limits CHECK (max_withdraw_per_transaction > 0
                                 AND max_deposit_per_transaction > 0
                                 AND note_multiple > 0)
);

-- Admin 0..* --manages-- 0..* Atm   (many-to-many)
CREATE TABLE admin_atms (
    admin_id VARCHAR(36) NOT NULL,
    atm_id   BIGINT      NOT NULL,
    PRIMARY KEY (admin_id, atm_id),
    CONSTRAINT fk_admin_atms_admin FOREIGN KEY (admin_id) REFERENCES users (user_id) ON DELETE CASCADE,
    CONSTRAINT fk_admin_atms_atm   FOREIGN KEY (atm_id)   REFERENCES atms (atm_id)   ON DELETE CASCADE
);

-- ---------------------------------------------------------------------
-- CASH CASSETTES  (Atm 1 <>-- cash trays 1..* CashCassette)
-- ---------------------------------------------------------------------
CREATE TABLE cash_cassettes (
    cassette_id   VARCHAR(36) PRIMARY KEY,
    atm_id        BIGINT      NOT NULL,
    denomination  INT         NOT NULL,
    note_count    INT         NOT NULL DEFAULT 0,
    capacity      INT         NOT NULL,
    low_threshold INT         NOT NULL DEFAULT 0,
    CONSTRAINT fk_cassettes_atm   FOREIGN KEY (atm_id) REFERENCES atms (atm_id) ON DELETE CASCADE,
    CONSTRAINT uq_cassette_denom  UNIQUE (atm_id, denomination),
    CONSTRAINT ck_cassette_values CHECK (denomination > 0
                                     AND note_count >= 0
                                     AND capacity > 0
                                     AND note_count <= capacity
                                     AND low_threshold >= 0)
);

-- ---------------------------------------------------------------------
-- ATM ALERTS  (Atm 1 <>-- raises --> 0..* AtmAlert, resolvedBy Admin 0..1)
-- ---------------------------------------------------------------------
CREATE TABLE atm_alerts (
    alert_id     VARCHAR(36)  PRIMARY KEY,
    atm_id       BIGINT       NOT NULL,
    type         VARCHAR(20)  NOT NULL,
    message      VARCHAR(500),
    created_at   TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at  TIMESTAMP,
    resolved_by  VARCHAR(36),
    CONSTRAINT fk_alerts_atm      FOREIGN KEY (atm_id)      REFERENCES atms (atm_id) ON DELETE CASCADE,
    CONSTRAINT fk_alerts_resolver FOREIGN KEY (resolved_by) REFERENCES users (user_id),
    CONSTRAINT ck_alerts_type     CHECK (type IN ('CASH_LOW', 'OFFLINE', 'HARDWARE_FAULT')),
    CONSTRAINT ck_alerts_resolved CHECK ((resolved_at IS NULL AND resolved_by IS NULL)
                                      OR (resolved_at IS NOT NULL AND resolved_by IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- SESSIONS
--   Session 0..* --hosted on--> 1 Atm
--   Session 0..* --customer--> 1 User
--   Session 0..* --authenticatedBy--> 0..1 Card  (null when login by credentials)
-- ---------------------------------------------------------------------
CREATE TABLE sessions (
    session_id      VARCHAR(36) PRIMARY KEY,
    atm_id          BIGINT      NOT NULL,
    user_id         VARCHAR(36) NOT NULL,
    card_number     VARCHAR(19),
    started_at      TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_activity   TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP,
    timeout_seconds INT         NOT NULL DEFAULT 120,
    auth_method     VARCHAR(12) NOT NULL,
    status          VARCHAR(10) NOT NULL DEFAULT 'ACTIVE',
    CONSTRAINT fk_sessions_atm  FOREIGN KEY (atm_id)      REFERENCES atms (atm_id),
    CONSTRAINT fk_sessions_user FOREIGN KEY (user_id)     REFERENCES users (user_id),
    CONSTRAINT fk_sessions_card FOREIGN KEY (card_number) REFERENCES cards (card_number),
    CONSTRAINT ck_sessions_auth    CHECK (auth_method IN ('CARD', 'CREDENTIALS')),
    CONSTRAINT ck_sessions_status  CHECK (status IN ('ACTIVE', 'CLOSED', 'EXPIRED', 'LOCKED')),
    CONSTRAINT ck_sessions_timeout CHECK (timeout_seconds > 0),
    CONSTRAINT ck_sessions_card    CHECK ((auth_method = 'CARD' AND card_number IS NOT NULL)
                                       OR (auth_method = 'CREDENTIALS' AND card_number IS NULL))
);

-- ---------------------------------------------------------------------
-- TRANSACTIONS
--   Transaction (abstract) <|-- FinancialTransaction <|-- Transfer/Withdrawal/Deposit
--                          <|-- BalanceInquiry, PinChange
--   Base table holds common columns (+ amount for financial types);
--   subtype-specific columns go in *_details tables.
--   Session 1 --performs--> 0..* Transaction
--   Atm 1 --executes--> 0..* Transaction
--   Account 1 --ledger--> 0..* Transaction  (source account)
-- ---------------------------------------------------------------------
CREATE TABLE transactions (
    transaction_id  VARCHAR(36)    PRIMARY KEY,
    tx_type         VARCHAR(20)    NOT NULL,
    session_id      VARCHAR(36)    NOT NULL,
    atm_id          BIGINT         NOT NULL,
    account_number  VARCHAR(20)    NOT NULL,
    amount          DECIMAL(19, 2),
    status          VARCHAR(10)    NOT NULL DEFAULT 'PENDING',
    created_at      TIMESTAMP      NOT NULL DEFAULT CURRENT_TIMESTAMP,
    failure_reason  VARCHAR(255),
    CONSTRAINT fk_tx_session FOREIGN KEY (session_id)     REFERENCES sessions (session_id),
    CONSTRAINT fk_tx_atm     FOREIGN KEY (atm_id)         REFERENCES atms (atm_id),
    CONSTRAINT fk_tx_account FOREIGN KEY (account_number) REFERENCES accounts (account_number),
    CONSTRAINT ck_tx_type    CHECK (tx_type IN ('WITHDRAWAL', 'DEPOSIT', 'TRANSFER',
                                                'BALANCE_INQUIRY', 'PIN_CHANGE')),
    CONSTRAINT ck_tx_status  CHECK (status IN ('PENDING', 'SUCCESS', 'FAILED', 'REVERSED', 'CANCELLED')),
    -- amount مطلوب وموجب للعمليات المالية فقط
    CONSTRAINT ck_tx_amount  CHECK (
        (tx_type IN ('WITHDRAWAL', 'DEPOSIT', 'TRANSFER') AND amount IS NOT NULL AND amount > 0)
     OR (tx_type IN ('BALANCE_INQUIRY', 'PIN_CHANGE')     AND amount IS NULL)
    )
);

-- TransferTransaction -> destination account
CREATE TABLE transfer_details (
    transaction_id       VARCHAR(36) PRIMARY KEY,
    destination_account  VARCHAR(20) NOT NULL,
    CONSTRAINT fk_transfer_tx   FOREIGN KEY (transaction_id)      REFERENCES transactions (transaction_id) ON DELETE CASCADE,
    CONSTRAINT fk_transfer_dest FOREIGN KEY (destination_account) REFERENCES accounts (account_number)
);

-- DepositTransaction -> depositType, chequeNumber [0..1]
CREATE TABLE deposit_details (
    transaction_id  VARCHAR(36) PRIMARY KEY,
    deposit_type    VARCHAR(10) NOT NULL,
    cheque_number   VARCHAR(30),
    CONSTRAINT fk_deposit_tx     FOREIGN KEY (transaction_id) REFERENCES transactions (transaction_id) ON DELETE CASCADE,
    CONSTRAINT ck_deposit_type   CHECK (deposit_type IN ('CASH', 'CHEQUE')),
    CONSTRAINT ck_deposit_cheque CHECK ((deposit_type = 'CHEQUE' AND cheque_number IS NOT NULL)
                                     OR (deposit_type = 'CASH'   AND cheque_number IS NULL))
);

-- PinChangeTransaction -> Card (0..* PinChange --for--> 1 Card)
CREATE TABLE pin_change_details (
    transaction_id  VARCHAR(36) PRIMARY KEY,
    card_number     VARCHAR(19) NOT NULL,
    CONSTRAINT fk_pinchange_tx   FOREIGN KEY (transaction_id) REFERENCES transactions (transaction_id) ON DELETE CASCADE,
    CONSTRAINT fk_pinchange_card FOREIGN KEY (card_number)    REFERENCES cards (card_number)
);

-- ---------------------------------------------------------------------
-- SERVICE REQUESTS
--   Customer 1 --submits--> 0..* ServiceRequest
--   ServiceRequest 0..* --about--> 0..1 Account / 0..1 Card
--   Admin 0..1 --reviews--> 0..* ServiceRequest
-- ---------------------------------------------------------------------
CREATE TABLE service_requests (
    request_id      VARCHAR(36)  PRIMARY KEY,
    customer_id     VARCHAR(36)  NOT NULL,
    type            VARCHAR(20)  NOT NULL,
    status          VARCHAR(10)  NOT NULL DEFAULT 'PENDING',
    reason          VARCHAR(500),
    review_note     VARCHAR(500),
    account_number  VARCHAR(20),
    card_number     VARCHAR(19),
    reviewed_by     VARCHAR(36),
    created_at      TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at     TIMESTAMP,
    CONSTRAINT fk_req_customer FOREIGN KEY (customer_id)    REFERENCES users (user_id),
    CONSTRAINT fk_req_account  FOREIGN KEY (account_number) REFERENCES accounts (account_number),
    CONSTRAINT fk_req_card     FOREIGN KEY (card_number)    REFERENCES cards (card_number),
    CONSTRAINT fk_req_admin    FOREIGN KEY (reviewed_by)    REFERENCES users (user_id),
    CONSTRAINT ck_req_type     CHECK (type IN ('FREEZE_ACCOUNT', 'UNFREEZE_ACCOUNT', 'BLOCK_CARD')),
    CONSTRAINT ck_req_status   CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    -- الطلب بيخص حساب أو كارت حسب النوع
    CONSTRAINT ck_req_target   CHECK (
        (type IN ('FREEZE_ACCOUNT', 'UNFREEZE_ACCOUNT') AND account_number IS NOT NULL AND card_number IS NULL)
     OR (type = 'BLOCK_CARD'                            AND card_number IS NOT NULL AND account_number IS NULL)
    ),
    CONSTRAINT ck_req_review   CHECK ((status = 'PENDING' AND reviewed_by IS NULL AND resolved_at IS NULL)
                                   OR (status <> 'PENDING' AND reviewed_by IS NOT NULL AND resolved_at IS NOT NULL))
);

-- ---------------------------------------------------------------------
-- AUDIT LOGS  (User 0..1 --actor--> 0..* AuditLog)
-- ---------------------------------------------------------------------
CREATE TABLE audit_logs (
    log_id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor_id    VARCHAR(36),
    action      VARCHAR(20)  NOT NULL,
    details     VARCHAR(1000),
    atm_id      BIGINT,
    target_id   VARCHAR(50),
    created_at  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_audit_actor FOREIGN KEY (actor_id) REFERENCES users (user_id) ON DELETE SET NULL,
    CONSTRAINT fk_audit_atm   FOREIGN KEY (atm_id)   REFERENCES atms (atm_id)   ON DELETE SET NULL,
    CONSTRAINT ck_audit_action CHECK (action IN ('LOGIN', 'LOGOUT', 'WITHDRAW', 'DEPOSIT', 'TRANSFER',
                                                 'PIN_CHANGE', 'CARD_BLOCKED', 'ACCOUNT_FROZEN',
                                                 'ATM_REFILLED'))
);

